#!/usr/bin/env node
/*
 * Builds MobileApp/android/app/src/main/assets/adult_domains.txt from a PINNED commit of
 * StevenBlack/hosts (alternates/porn-only, MIT). Deterministic: same commit -> byte-identical
 * output (sorted, LF endings, header carries the upstream commit and upstream date, never the
 * build date).
 *
 *   node scripts/build-adult-list.js
 *
 * Any domain that is, or is a subdomain of, an entry in never_block_domains.json is removed, so a
 * stray upstream entry can never block a search engine or social network. The never-block file is
 * the single source; the Java side reads the same file at runtime.
 *
 * To move to a newer upstream: change PINNED_COMMIT, re-run, review the diff, commit.
 */
'use strict';

const fs = require('fs');
const https = require('https');
const path = require('path');

const PINNED_COMMIT = 'cb5daa41eadded64f169ffe9b0cdee7000540d7f';
const UPSTREAM_PATH = 'alternates/porn-only/hosts';
const URL = `https://raw.githubusercontent.com/StevenBlack/hosts/${PINNED_COMMIT}/${UPSTREAM_PATH}`;

const ASSETS = path.join(__dirname, '..', 'MobileApp', 'android', 'app', 'src', 'main', 'assets');
const OUT = path.join(ASSETS, 'adult_domains.txt');
const NEVER_BLOCK = path.join(ASSETS, 'never_block_domains.json');

const SKIP = new Set([
  '0.0.0.0', 'localhost', 'localhost.localdomain', 'local', 'broadcasthost',
  'ip6-localhost', 'ip6-loopback', 'ip6-localnet', 'ip6-mcastprefix',
  'ip6-allnodes', 'ip6-allrouters', 'ip6-allhosts',
]);
const LABEL_RE = /^[a-z0-9_¡-￿-]+$/;

function fetch(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode !== 200) {
        reject(new Error(`HTTP ${res.statusCode} for ${url}`));
        res.resume();
        return;
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    }).on('error', reject);
  });
}

// Keep in sync with DomainMatcher.TWO_PART_SUFFIXES (Java). AdultAssetTest cross-checks the
// generated asset against the Java NeverBlockList, so drift shows up as a failing test.
const TWO_PART_SUFFIXES = new Set([
  'co.uk', 'org.uk', 'ac.uk', 'gov.uk', 'me.uk', 'com.tn', 'org.tn', 'gov.tn', 'nat.tn',
  'com.au', 'net.au', 'org.au', 'co.jp', 'ne.jp', 'or.jp', 'com.br', 'net.br', 'co.in',
  'net.in', 'org.in', 'com.eg', 'com.sa', 'co.za', 'com.tr', 'com.mx', 'co.nz', 'com.ar',
  'com.co', 'com.cn', 'com.hk', 'com.sg', 'com.my', 'com.pk', 'co.id', 'co.kr', 'com.ua',
  'com.ng',
]);

/**
 * Same semantics as NeverBlockList.java: exact/subdomain match, and "name.*" = the label "name"
 * followed by a one-label TLD or a known two-part suffix (google.com, google.co.uk, google.com.tn;
 * NOT google.porno.sexy).
 */
function neverBlockCovers(entries, host) {
  const labels = host.split('.');
  for (const entry of entries) {
    if (entry.endsWith('.*')) {
      const name = entry.slice(0, -2);
      for (let i = 0; i < labels.length; i++) {
        const rest = labels.slice(i + 1);
        if (labels[i] !== name) continue;
        if (rest.length === 1 || (rest.length === 2 && TWO_PART_SUFFIXES.has(rest.join('.')))) {
          return true;
        }
      }
    } else if (host === entry || host.endsWith('.' + entry)) {
      return true;
    }
  }
  return false;
}

function parse(text) {
  const dateMatch = text.match(/^# Date: (.+)$/m);
  const upstreamDate = dateMatch ? dateMatch[1].trim() : 'unknown';
  const domains = new Set();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line.startsWith('0.0.0.0 ')) continue;
    const host = line.slice(8).split('#')[0].trim().toLowerCase();
    if (!host || SKIP.has(host) || host.indexOf('.') < 0) continue;
    if (!host.split('.').every((l) => l.length > 0 && LABEL_RE.test(l))) continue;
    domains.add(host);
  }
  return {upstreamDate, domains};
}

async function main() {
  const config = JSON.parse(fs.readFileSync(NEVER_BLOCK, 'utf8'));
  const neverBlock = config.neverBlock;
  // Shared-hosting platforms: an exact blog host (x.blogspot.com) is a legitimate list entry, but
  // the bare platform (blogspot.com) would block every blog on it, so it is never listed.
  const sharedSuffixes = new Set(config.exactHostOnly);
  const {upstreamDate, domains} = parse(await fetch(URL));

  let removed = 0;
  const kept = [];
  for (const d of domains) {
    if (neverBlockCovers(neverBlock, d) || sharedSuffixes.has(d)) {
      removed++;
    } else {
      kept.push(d);
    }
  }
  kept.sort();

  const header = [
    '# SafeGuard adult-domain list (Phase B). GENERATED by scripts/build-adult-list.js — do not edit.',
    '# Source: StevenBlack/hosts, alternates/porn-only, MIT License (see NOTICE)',
    `# Upstream commit: ${PINNED_COMMIT}`,
    `# Upstream date: ${upstreamDate}`,
    `# Entries: ${kept.length}`,
    `# Removed because they are never-block domains (or subdomains) or a bare shared-hosting suffix: ${removed}`,
    '',
  ];
  fs.writeFileSync(OUT, header.join('\n') + kept.join('\n') + '\n', 'utf8');
  console.log(`wrote ${OUT}: ${kept.length} domains, removed ${removed} never-block, upstream ${upstreamDate}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
